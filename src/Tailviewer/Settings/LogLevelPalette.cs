namespace Tailviewer.Settings
{
	/// <summary>
	///     Determines which default palette is used for log levels that have not
	///     been customized by the user.
	/// </summary>
	public enum LogLevelPalette
	{
		/// <summary>
		///     Use the light log level palette.
		/// </summary>
		Light = 0,

		/// <summary>
		///     Use the dark log level palette.
		/// </summary>
		Dark = 1
	}
}
